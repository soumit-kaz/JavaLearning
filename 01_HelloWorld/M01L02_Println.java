public class M01L02_Println {

    public static void main(String[] args) {
        // println prints the text and then ends the line
        System.out.println("one");
        System.out.println("two");

        // println with nothing inside prints a blank line
        System.out.println();

        // spaces inside the quotes are printed exactly
        System.out.println("   indented");

        // one println per row can draw a picture
        System.out.println("  *");
        System.out.println(" ***");
        System.out.println("*****");
    }
}
