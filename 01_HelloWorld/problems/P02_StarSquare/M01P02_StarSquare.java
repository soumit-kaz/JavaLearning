public class M01P02_StarSquare {

    public static void main(String[] args) {
        // a full square: every row is the same
        System.out.println("*****");
        System.out.println("*****");
        System.out.println("*****");
        System.out.println("*****");
        System.out.println("*****");

        System.out.println();

        // a hollow square: only the first and last rows are full
        System.out.println("*****");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*   *");
        System.out.println("*****");
    }
}
